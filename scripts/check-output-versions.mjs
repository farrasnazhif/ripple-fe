import assert from "node:assert/strict";
import { outputHistory } from "../src/lib/output-versions.ts";
const versions = [1, 2, 3, 4].map(id => ({ id: String(id), created_at: `2026-10-10T00:00:0${id}Z` }));
assert.deepEqual(outputHistory(versions).map(v => v.id), ["4", "3", "2", "1"]);
assert.deepEqual(outputHistory([...versions].reverse()).map(v => v.id), ["4", "3", "2", "1"]);
assert.deepEqual(outputHistory([]), []);
assert.equal(outputHistory([versions[0]]).length, 1);
assert.equal(versions.length, 4);
const labels = outputHistory(versions).map((version, index) => index === 0 ? "Current" : `Version ${versions.length - index}`);
assert.deepEqual(labels, ["Current", "Version 3", "Version 2", "Version 1"]);
console.log("Output history retains Current and every previous numbered version.");
